import {
  cp,
  mkdir,
  mkdtemp,
  rm,
  symlink,
  unlink,
  writeFile,
} from "node:fs/promises";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { preparePagesOutput } from "./pages-output.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const stagingRoot = path.join(root, ".pages-build");
const destination = path.join(root, "out");
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || "/Vmeste";
if (!/^\/[A-Za-z0-9_-]+$/.test(basePath))
  throw new Error(
    "Use a single repository name for NEXT_PUBLIC_BASE_PATH, for example /Vmeste.",
  );
await mkdir(stagingRoot, { recursive: true });
const stage = await mkdtemp(path.join(stagingRoot, "export-"));
let linked = false;
try {
  // Explicit allowlist: no credentials, daily counters, documents or local .env files.
  for (const filename of [
    "package.json",
    "package-lock.json",
    "next.config.ts",
    "tsconfig.json",
    "next-env.d.ts",
  ])
    await cp(path.join(root, filename), path.join(stage, filename));
  await cp(path.join(root, "src"), path.join(stage, "src"), {
    recursive: true,
    filter: (source) => {
      const relative = path
        .relative(path.join(root, "src"), source)
        .split(path.sep)
        .join("/");
      return (
        relative !== "app/api" &&
        !relative.startsWith("app/api/") &&
        !/\.test\.[cm]?[jt]sx?$/.test(relative)
      );
    },
  });
  await cp(path.join(root, "public"), path.join(stage, "public"), {
    recursive: true,
  });
  await symlink(
    path.join(root, "node_modules"),
    path.join(stage, "node_modules"),
    process.platform === "win32" ? "junction" : "dir",
  );
  linked = true;
  const result = spawnSync(
    process.execPath,
    [
      path.join(root, "node_modules/next/dist/bin/next"),
      "build",
      stage,
      "--webpack",
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: {
        ...process.env,
        NEXT_PUBLIC_STATIC_EXPORT: "true",
        NEXT_PUBLIC_BASE_PATH: basePath,
        NEXT_TELEMETRY_DISABLED: "1",
      },
    },
  );
  if (result.error || result.status !== 0)
    throw new Error("GitHub Pages build failed.");
  if (
    path.dirname(destination) !== root ||
    path.basename(destination) !== "out"
  )
    throw new Error("Invalid output directory.");
  await preparePagesOutput(root);
  await cp(path.join(stage, "out"), destination, { recursive: true });
  await writeFile(path.join(destination, ".nojekyll"), "");
  await writeFile(
    path.join(destination, ".vmeste-pages-output"),
    "Generated by npm run build:pages\n",
  );
  console.log(`Static site ready in out/ for ${basePath}/`);
} finally {
  if (linked) await unlink(path.join(stage, "node_modules"));
  if (
    path.dirname(stage) !== stagingRoot ||
    !path.basename(stage).startsWith("export-")
  )
    throw new Error("Invalid staging directory.");
  await rm(stage, { recursive: true, force: true });
}
