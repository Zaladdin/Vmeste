import { afterEach, describe, expect, it } from "vitest";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { preparePagesOutput } from "../../scripts/pages-output.mjs";
const roots: string[] = [];
async function setup() {
  const root = await mkdtemp(path.join(tmpdir(), "vmeste-pages-test-"));
  roots.push(root);
  await mkdir(path.join(root, "out"));
  return root;
}
afterEach(async () => {
  for (const root of roots.splice(0))
    if (
      path.dirname(root) === tmpdir() &&
      path.basename(root).startsWith("vmeste-pages-test-")
    )
      await rm(root, { recursive: true, force: true });
});
describe("Pages output safety", () => {
  it("refuses any existing unmarked output, even without index.html", async () => {
    const root = await setup();
    await writeFile(path.join(root, "out", "private.txt"), "keep");
    await expect(preparePagesOutput(root)).rejects.toThrow(/marker/);
    expect(await readFile(path.join(root, "out", "private.txt"), "utf8")).toBe(
      "keep",
    );
  });
  it("clears only the previous marked generated output", async () => {
    const root = await setup();
    await writeFile(
      path.join(root, "out", ".vmeste-pages-output"),
      "Generated by npm run build:pages\n",
    );
    await preparePagesOutput(root);
    await expect(
      readFile(path.join(root, "out", ".vmeste-pages-output")),
    ).rejects.toMatchObject({ code: "ENOENT" });
  });
});
