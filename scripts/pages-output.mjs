import { lstat, readFile, rm } from "node:fs/promises";
import path from "node:path";

/** Refuse to replace or publish any unrelated output, including an empty folder. */
export async function preparePagesOutput(projectRoot) {
  const root = path.resolve(projectRoot);
  const destination = path.join(root, "out");
  let info;
  try {
    info = await lstat(destination);
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  if (!info.isDirectory() || info.isSymbolicLink())
    throw new Error(
      "Existing out directory has no valid Vmeste output marker.",
    );
  let marker;
  try {
    marker = await readFile(
      path.join(destination, ".vmeste-pages-output"),
      "utf8",
    );
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (marker !== "Generated by npm run build:pages\n")
    throw new Error(
      "Existing out directory has no valid Vmeste output marker.",
    );
  if (
    path.dirname(destination) !== root ||
    path.basename(destination) !== "out"
  )
    throw new Error("Invalid output directory.");
  await rm(destination, { recursive: true, force: true });
}
